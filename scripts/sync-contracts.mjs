// Copies the API contract (zod schemas + types) from the web repo into
// ./contracts, verbatim. The web repo's lib/contracts is the source of truth:
// never edit files in ./contracts by hand, re-run this script instead.
//
//   node scripts/sync-contracts.mjs [path-to-web-repo]
//
// Default web repo path: ../LinknSmile (sibling folder).
import { execSync } from "node:child_process";
import { cpSync, existsSync, mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const webRepo = resolve(root, process.argv[2] ?? "../LinknSmile");
const source = join(webRepo, "lib", "contracts");
const target = join(root, "contracts");

if (!existsSync(source)) {
  console.error(`Contract folder not found: ${source}`);
  process.exit(1);
}

const git = (args) => {
  try {
    return execSync(`git -C "${webRepo}" ${args}`, { encoding: "utf8" }).trim();
  } catch {
    return null;
  }
};

rmSync(target, { recursive: true, force: true });
mkdirSync(target, { recursive: true });
const files = readdirSync(source).filter((f) => f.endsWith(".ts"));
for (const file of files) cpSync(join(source, file), join(target, file));

const dirty = git("status --porcelain -- lib/contracts");
writeFileSync(
  join(target, "SOURCE.json"),
  JSON.stringify(
    {
      note: "Generated by scripts/sync-contracts.mjs. Do not edit files in this folder by hand.",
      sourceRepo: "LinknSmile (web) — lib/contracts",
      commit: git("rev-parse HEAD"),
      uncommittedChanges: dirty ? dirty.split("\n").length : 0,
      files,
    },
    null,
    2
  ) + "\n"
);

console.log(`Synced ${files.length} contract files from ${source}`);
